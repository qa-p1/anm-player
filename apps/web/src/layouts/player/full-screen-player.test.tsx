import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { MemoryRouter } from "react-router";
import { afterEach, expect, it, vi } from "vitest";
import { FullScreenPlayer } from "@/layouts/player/full-screen-player";
import { usePlayerStore } from "@/stores/player-store";
import { playerTrack, song } from "@/test/music-fixtures";
const server = vi.hoisted(() => ({ favorited: false }));
vi.mock("@/services/music-api", () => ({ listFavorites: vi.fn(async () => ({ songs: server.favorited ? [{ ...song(), is_favorited: true }] : [], artists: [], albums: [], playlists: [], library_albums: [], library_tracks: [] })), toggleFavorite: vi.fn(async () => { server.favorited = !server.favorited; return { is_favorited: server.favorited }; }) }));
vi.mock("@/services/audio-service", () => ({ audioService: {} }));
vi.mock("@/components/menus/track-actions-menu", () => ({ TrackActionsMenu: () => null }));
vi.mock("@/components/player/lyrics-panel", () => ({ LyricsPanel: () => null }));
vi.mock("@/components/player/player-tools-panel", () => ({ PlayerToolsPanel: () => null }));
vi.mock("@/components/player/queue-panel", () => ({ QueuePanel: () => null }));
vi.mock("@/components/ui/toast", () => ({ toast: vi.fn() }));
afterEach(cleanup);
it("keeps the favorite heart correct after closing and reopening the player", async () => {
  server.favorited = false;
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  usePlayerStore.setState({ currentSong: playerTrack(), isPlaying: false });
  const view = () => <QueryClientProvider client={client}><MemoryRouter><FullScreenPlayer onClose={() => {}} /></MemoryRouter></QueryClientProvider>;
  const first = render(view());
  fireEvent.click(await screen.findByRole("button", { name: "Add to favorites" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Remove from favorites" })).toBeInTheDocument());
  first.unmount();
  render(view());
  expect(await screen.findByRole("button", { name: "Remove from favorites" })).toBeInTheDocument();
  client.clear();
});
